#!/usr/bin/env python3
"""
Industrial PPE Retraining Dataset Collector
==========================================
Captures clean, unannotated video frames from CCTV cameras and pairs them with
standard YOLO format annotation files (.txt) generated by the deep learning model.

Key Features:
- Saves raw unannotated frames (NO bounding boxes baked into image pixels) for retraining.
- Generates standard normalized YOLO annotation files: <class_id> <x_center> <y_center> <width> <height>.
- Automatically creates `data.yaml` and `classes.txt` for 100% plug-and-play training or Label Studio/CVAT editing.
- Uploads dataset directly to S3 (`retraining_dataset/images/` and `retraining_dataset/labels/`) with local backup.
- Configurable collection duration (e.g. `--days 3` or `--hours 72`) and sampling rate.
- Focuses on frames with detections (including lower-confidence hard examples) to capture false positives for retraining.
"""

