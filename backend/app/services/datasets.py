"""Freezing the approved training pool into a versioned YOLO dataset.

datasets/<name>/images/{train,val}/<sample_id>.jpg
datasets/<name>/labels/{train,val}/<sample_id>.txt
datasets/<name>/data.yaml
"""
import hashlib
import logging
import threading
from collections import Counter, defaultdict

from sqlalchemy import select

from app.core.security import utcnow
from app.db.models import DatasetSample, DatasetVersion, ModelClass, Sample
from app.db.session import SessionLocal
from app.services.samples import yolo_txt
from app.services.storage import copy_into_main, get_storage

log = logging.getLogger(__name__)


def _rank(sample_id: int) -> str:
    # Deterministic pseudo-random order, so splits don't depend on insertion order
    return hashlib.sha1(f"split:{sample_id}".encode()).hexdigest()


def assign_splits(samples: list[Sample], val_ratio: float) -> None:
    """Gives every sample without a split one, stratified by camera area.

    A sample keeps its split forever. Otherwise an image validated on in v1 could be
    trained on in v2, and the metrics would look better than they are."""
    groups: dict[tuple, list[Sample]] = defaultdict(list)
    for s in samples:
        groups[(s.production_house or "", s.area or "")].append(s)
    for members in groups.values():
        target_val = round(len(members) * val_ratio)
        current_val = sum(1 for s in members if s.split == "val")
        for s in sorted((m for m in members if m.split is None), key=lambda m: _rank(m.id)):
            if current_val < target_val:
                s.split = "val"
                current_val += 1
            else:
                s.split = "train"


def _yaml_str(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def data_yaml(class_names: list[str]) -> str:
    lines = [
        "# Generated by the PPE platform. trainer.py rewrites `path` for its local copy.",
        "path: .",
        "train: images/train",
        "val: images/val",
        f"nc: {len(class_names)}",
        "names:",
    ]
    lines += [f"  {i}: {_yaml_str(name)}" for i, name in enumerate(class_names)]
    return "\n".join(lines) + "\n"


def build(dataset_id: int) -> None:
    """Runs in a background thread with its own session."""
    storage = get_storage()
    with SessionLocal() as db:
        ds = db.get(DatasetVersion, dataset_id)
        try:
            samples = db.scalars(select(Sample).where(Sample.status == "approved").order_by(Sample.id)).all()
            if not samples:
                raise ValueError("The training pool is empty. Approve some annotated images first.")
            assign_splits(samples, ds.val_ratio)
            db.flush()

            class_names = [c.name for c in db.scalars(select(ModelClass).order_by(ModelClass.class_id)).all()]
            counts = {"train": Counter(), "val": Counter()}
            images = Counter()
            base = ds.s3_prefix
            for s in samples:
                copy_into_main(s.image_key, f"{base}/images/{s.split}/{s.id}.jpg")
                storage.put_bytes(f"{base}/labels/{s.split}/{s.id}.txt", yolo_txt(s.labels).encode(), "text/plain")
                images[s.split] += 1
                for lb in s.labels:
                    counts[s.split][class_names[lb.class_id]] += 1
                db.add(DatasetSample(dataset_version_id=ds.id, sample_id=s.id, split=s.split))
            storage.put_bytes(f"{ds.s3_prefix}/data.yaml", data_yaml(class_names).encode(), "text/yaml")

            ds.class_names = class_names
            ds.class_counts = {split: dict(c) for split, c in counts.items()}
            ds.sample_count = len(samples)
            ds.train_count = images["train"]
            ds.val_count = images["val"]
            ds.status = "ready"
            if ds.val_count == 0:
                ds.notes = ((ds.notes or "") + "\nNo validation images: add more samples per area.").strip()
        except Exception as e:  # noqa: BLE001 - recorded on the dataset row
            log.exception("Dataset build %s failed", dataset_id)
            db.rollback()
            ds = db.get(DatasetVersion, dataset_id)
            ds.status = "failed"
            ds.error = str(e)
        ds.finished_at = utcnow()
        db.commit()


def start_build(dataset_id: int) -> None:
    threading.Thread(target=build, args=(dataset_id,), name=f"dataset-{dataset_id}", daemon=True).start()
